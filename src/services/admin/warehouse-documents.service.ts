          documentId,
          productId: item.productId,
          barcodeId: item.barcodeId,
          baseQuantity: item.baseQuantity,
          quantityMultiplier: item.quantityMultiplier,
          unitPrice: item.unitPrice,
          reservationId: item.reservationId,
