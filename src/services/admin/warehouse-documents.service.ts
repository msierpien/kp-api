/**
 * Rezerwacja przypieta do pozycji WZ moze byc juz nieaktywna, jesli zamowienie
 * zmienilo status (np. na SHIPPED) zanim ktos zatwierdzil roboczy dokument.
 * Zwolnienie rezerwacji LOCAL_STOCK oddaje towar na stan, wiec taka pozycja musi
 * przy zatwierdzeniu zdjac stan samodzielnie (DETACH). Rezerwacje hurtowe nigdy
 * nie ruszaly stanu, wiec zostaja bez zmiany stanu (SKIP).
 */
type WzReservationDisposition = 'CONSUME' | 'DETACH' | 'DETACH_CANCEL' | 'SKIP';

async function resolveWzReservationDispositions(
  type: DocumentType,
  items: Array<{ id: string; reservationId?: string | null }>,
): Promise<Map<string, WzReservationDisposition>> {
  const dispositions = new Map<string, WzReservationDisposition>();
  if (type !== 'WZ') return dispositions;

  const reservationIds = items
    .map((item) => item.reservationId)
    .filter((reservationId): reservationId is string => Boolean(reservationId));
  if (reservationIds.length === 0) return dispositions;

  const reservations = await prisma.warehouseReservation.findMany({
    where: { id: { in: reservationIds } },
    select: { id: true, status: true, source: true },
  });
  const reservationById = new Map(reservations.map((reservation) => [reservation.id, reservation]));

  for (const item of items) {
    if (!item.reservationId) continue;
    const reservation = reservationById.get(item.reservationId);
    if (!reservation) {
      dispositions.set(item.id, 'DETACH');
      continue;
    }
    if (reservation.status === 'ACTIVE' && reservation.source === 'WHOLESALE_BACKORDER') {
      // Backorder nie zajal stanu, wiec wydanie musi zdjac stan samo, a rezerwacje
      // hurtowa zamykamy — towar wyjezdza, nie ma juz czego domawiac.
      dispositions.set(item.id, 'DETACH_CANCEL');
      continue;
    }
    if (reservation.status === 'ACTIVE' || reservation.status === 'CONSUMED') {
      dispositions.set(item.id, 'CONSUME');
      continue;
    }
    dispositions.set(item.id, reservation.source === 'LOCAL_STOCK' ? 'DETACH' : 'SKIP');
  }

  return dispositions;
}

export async function confirmDocument(id: string) {
  const tenantId = getTenantId();
  const context = getTenantContext();
  const where: any = { id };
  if (tenantId) where.tenantId = tenantId;

  const doc = await prisma.warehouseDocument.findFirst({
    where,
    include: { items: { include: { product: true } } },
  });
  if (!doc) throw new Error('Dokument nie znaleziony');
  if (doc.status !== 'DRAFT') throw new Error('Tylko dokumenty DRAFT można zatwierdzić');

  if (doc.items.length === 0) throw new Error('Dokument nie ma żadnych pozycji');

  const dispositions = await resolveWzReservationDispositions(doc.type, doc.items);
  // Pozycje z martwa rezerwacja (LOCAL_STOCK juz zwolniona) oraz z aktywnym backorderem
  // musza same zdjac stan — rezerwacja albo oddala towar na magazyn, albo nigdy go nie zajela.
  const isDetached = (item: { id: string }) => {
    const disposition = dispositions.get(item.id);
    return disposition === 'DETACH' || disposition === 'DETACH_CANCEL';
  };
  const stockItems = doc.items.map((item) => (
    isDetached(item) ? { ...item, reservationId: null } : item
  ));
  const consumableItems = doc.items.filter((item) => dispositions.get(item.id) === 'CONSUME');
  const detachedItemIds = doc.items.filter(isDetached).map((item) => item.id);
  const backorderReservationIdsToCancel = doc.items
    .filter((item) => dispositions.get(item.id) === 'DETACH_CANCEL')
    .map((item) => item.reservationId)
    .filter((reservationId): reservationId is string => Boolean(reservationId));

  await assertFullInventoryComplete(doc.tenantId, doc.type, doc.metadataJson, doc.items);
  await assertCanConfirmWithoutNegativeStock(doc.tenantId, doc.type, stockItems);

  const confirmedDocument = await prisma.$transaction(async (tx) => {
    await applyIncomingPurchaseCosts(tx, doc.type, doc.items);
    await applyStockDeltas(tx, doc.type, stockItems);
    await consumeDocumentReservations(tx, consumableItems);
    if (detachedItemIds.length > 0) {
      await tx.warehouseDocumentItem.updateMany({
        where: { id: { in: detachedItemIds } },
        data: { reservationId: null },
      });
    }
    if (backorderReservationIdsToCancel.length > 0) {
      // Bez ruchu stanu: backorder nigdy nie zajal currentStock.
      await tx.warehouseReservation.updateMany({
        where: { id: { in: backorderReservationIdsToCancel }, status: 'ACTIVE' },
        data: {
          status: 'CANCELLED',
          cancelledAt: new Date(),
          reason: 'Pozycja wydana dokumentem WZ bez pokrycia lokalnego',
        },
      });
    }

    return tx.warehouseDocument.update({
      where: { id },
      data: {
        status: 'CONFIRMED',
        confirmedAt: new Date(),
        confirmedByUserId: context?.userId,
      },
        include: documentDetailInclude,
    });
  }, { timeout: 20000 });

  const affectedProductIds = Array.from(new Set(doc.items.map((item) => item.productId)));
  if (doc.type === 'PZ') {
    await reallocateWholesaleBackordersForProducts(doc.tenantId, affectedProductIds);
  }

  await syncStockForProducts(
    affectedProductIds,
    'DOCUMENT_CONFIRM',
    id,
  );

  return confirmedDocument;
}

async function reallocateWholesaleBackordersForProducts(tenantId: string, productIds: string[]) {
  const uniqueProductIds = Array.from(new Set(productIds.filter(Boolean)));
  if (uniqueProductIds.length === 0) return;

  const reservations = await prisma.warehouseReservation.findMany({
    where: {
      tenantId,
      status: 'ACTIVE',
      source: 'WHOLESALE_BACKORDER',
      warehouseProductId: { in: uniqueProductIds },
      order: {
        operationalStatus: { in: STOCK_RESERVATION_ORDER_OPERATIONAL_STATUSES },
      },
    },
    select: { orderId: true },
  });

  const orderIds = Array.from(new Set(reservations.map((reservation) => reservation.orderId)));
  for (const orderId of orderIds) {
    await reserveOrder(orderId);
  }

  // Realokacja wymienila rezerwacje (nowe id) — robocze WZ tych zamowien musza
  // dostac pozycje wskazujace nowe rezerwacje, inaczej zatwierdzenie nie zdejmie stanu.
  if (orderIds.length > 0) {
    const draftDocuments = await prisma.warehouseDocument.findMany({
      where: { tenantId, orderId: { in: orderIds }, type: 'WZ', status: 'DRAFT' },
      select: { id: true },
    });
    for (const draft of draftDocuments) {
      await syncWzDraftItemsWithReservations(draft.id);
    }
  }
}

async function assertCanConfirmWithoutNegativeStock(
  tenantId: string,
  type: DocumentType,
  items: Array<{ productId: string; quantity: Prisma.Decimal; systemQuantity?: Prisma.Decimal | null; reservationId?: string | null; product: { name: string; unit: string } }>,
) {
  if (type === 'INW') {
    for (const item of items) {
      if (Number(item.quantity) < 0) {
        throw new Error(`Stan policzony produktu "${item.product.name}" nie może być ujemny`);
      }
    }
    return;
  }

  if (!['WZ', 'RW'].includes(type)) return;

  const settings = await getWarehouseSettings(tenantId);
  if (settings.allowNegativeStock) return;

  const requestedByProduct = new Map<string, { quantity: number; name: string; unit: string }>();

  for (const item of items) {
    if (type === 'WZ' && item.reservationId) continue;

    const existing = requestedByProduct.get(item.productId);
    const quantity = Number(item.quantity);

    if (existing) {
      existing.quantity += quantity;
    } else {
      requestedByProduct.set(item.productId, {
        quantity,
        name: item.product.name,
        unit: item.product.unit,
      });
    }
  }

  if (requestedByProduct.size === 0) return;

  const products = await prisma.warehouseProduct.findMany({
    where: { tenantId, id: { in: Array.from(requestedByProduct.keys()) } },
    select: { id: true, currentStock: true },
  });
  const stockByProductId = new Map(products.map((product) => [product.id, Number(product.currentStock)]));

  for (const [productId, requested] of requestedByProduct) {
    const stock = stockByProductId.get(productId) ?? 0;
    const requestedQuantity = requested.quantity;
    const nextStock = stock - requestedQuantity;

    if (nextStock < 0) {
      throw new Error(
        `Niewystarczający stan produktu "${requested.name}": dostępne ${stock} ${requested.unit}, wymagane ${requestedQuantity} ${requested.unit}`,
      );
    }
  }
}

async function assertFullInventoryComplete(
  tenantId: string,
  type: string,
  metadataJson: Prisma.JsonValue | null,
  items: Array<{ productId: string }>,
) {
  if (type !== 'INW') return;
  const metadata = metadataRecord(metadataJson);
  if (metadata.inventoryScope !== FULL_INVENTORY_SCOPE) return;

  const activeProducts = await prisma.warehouseProduct.findMany({
    where: { tenantId, isActive: true, isStockTracked: true },
    select: { id: true, sku: true, name: true },
    orderBy: [{ sku: 'asc' }, { name: 'asc' }],
  });

  const itemProductIds = new Set(items.map((item) => item.productId));
  const missingProducts = activeProducts.filter((product) => !itemProductIds.has(product.id));
  if (missingProducts.length === 0) return;

  const preview = missingProducts
    .slice(0, 5)
    .map((product) => `${product.sku} ${product.name}`)
    .join(', ');
  const suffix = missingProducts.length > 5 ? ` i ${missingProducts.length - 5} kolejnych` : '';
  throw new Error(`Pełna inwentaryzacja wymaga policzenia wszystkich aktywnych produktów śledzonych w magazynie. Brakuje ${missingProducts.length}: ${preview}${suffix}`);
}

async function getWarehouseSettings(tenantId: string) {
  const tenant = await prisma.tenant.findUnique({
    where: { id: tenantId },
    select: { limitsJson: true },
  });

  const limits = tenant?.limitsJson as any;
  return {
    allowNegativeStock: limits?.warehouse?.allowNegativeStock === true,
    autoCreateWzOnOrder: limits?.warehouse?.autoCreateWzOnOrder !== false,
    autoConfirmWzOnOrder: limits?.warehouse?.autoConfirmWzOnOrder === true,
  };
}

export async function shouldAutoCreateWzForTenant(tenantId: string) {
  const settings = await getWarehouseSettings(tenantId);
  return settings.autoCreateWzOnOrder;
}

export async function cancelDocument(id: string, input: CancelDocumentInput = {}) {
  const tenantId = getTenantId();
  const context = getTenantContext();
  const where: any = { id };
  if (tenantId) where.tenantId = tenantId;

  const doc = await prisma.warehouseDocument.findFirst({
    where,
    include: { items: true },
  });
  if (!doc) throw new Error('Dokument nie znaleziony');
  if (doc.status === 'CANCELLED') throw new Error('Dokument jest już anulowany');

  const cancelledDocument = await prisma.$transaction(async (tx) => {
    if (doc.status === 'CONFIRMED') {
      await applyStockDeltas(tx, doc.type, doc.items, true);
      await releaseDocumentReservations(tx, doc.items);
    }

    return tx.warehouseDocument.update({
      where: { id },
      data: {
        status: 'CANCELLED',
        cancelledAt: new Date(),
        cancelledByUserId: context?.userId,
        cancelReason: input.reason,
      },
      include: documentDetailInclude,
    });
  });

  if (doc.status === 'CONFIRMED') {
    await syncStockForProducts(
      doc.items.map((item) => item.productId),
      'DOCUMENT_CANCEL',
      id,
    );
  }

  return cancelledDocument;
}

